import json, subprocess
from pathlib import Path
root=Path.cwd()
metadata=json.loads(subprocess.check_output(['cargo','metadata','--locked','--offline','--format-version','1']))
nodes={n['id']:n for n in metadata['resolve']['nodes']};pkgs={p['id']:p for p in metadata['packages']}
seen=set();todo=[d['pkg'] for d in nodes[metadata['resolve']['root']]['deps'] if any(k['kind']!='dev' for k in d['dep_kinds'])]
while todo:
 i=todo.pop()
 if i in seen:continue
 seen.add(i);todo.extend(d['pkg'] for d in nodes[i]['deps'])
notices=root/'licenses';notices.mkdir(exist_ok=True)
apache=(root/'vendor/partitions/LICENSE.txt').read_text()
rows=[]
for i in sorted(seen,key=lambda i:(pkgs[i]['name'],pkgs[i]['version'])):
 p=pkgs[i];source=Path(p['manifest_path']).parent
 files=sorted(f for f in source.rglob('*') if f.is_file() and f.name.upper().startswith(('LICENSE','COPYING','COPYRIGHT','LICENCE','NOTICE')))
 parts=[f"{p['name']} {p['version']}\nDeclared licence: {p['license']}\nAuthors: {', '.join(p['authors'])}\nRepository: {p['repository'] or ''}\n"]
 for f in files:parts.append(f"\n--- {f.relative_to(source)} ---\n\n"+f.read_text(errors='replace'))
 if not files:
  if p['name']=='cloudabi':
   text=(source/'cloudabi.rs').read_text().split('// This file is automatically generated.')[0]
   parts.append('\n'+'\n'.join(line.removeprefix('// ') for line in text.splitlines()))
  elif 'Apache-2.0' in p['license']:
   parts.append('\nDistributed under the Apache-2.0 option declared by this package.\n\n'+apache)
  else:raise RuntimeError(f"missing licence text: {p['name']}")
 filename=f"{p['name']}-{p['version']}.txt"
 (notices/filename).write_text('\n'.join(parts))
 rows.append(f"| {p['name']} | {p['version']} | {p['license']} | [notice](licenses/{filename}) |")
# skani's DNA lookup tables include miniprot's separate MIT notice.
text=(root/'vendor/skani/src/types.rs').read_text()
start=text.index('//The MIT License');end=text.index('//******************************',start)
(notices/'miniprot.txt').write_text('\n'.join(line.removeprefix('//').lstrip() for line in text[start:end].splitlines())+'\n')
(root/'THIRD-PARTY-LICENSES.md').write_text('''# Third-party licences

The locked runtime dependency graph, including target-specific dependencies, is listed below. Each notice retains the licence and copyright text shipped with its source package. For packages that declare Apache-2.0 but ship no separate licence file, the notice includes their declared authors and the Apache-2.0 text. Only dependencies selected for a build are linked into its binary.

skani is vendored from `22da4ae9e44b2e3e686c8e5c71fcd16cec2b9791` under its supplied MIT licence. Its modified files and compatibility semantics are documented in [the fork notes](vendor/README.md). The vendored partitions revision is `adf36eeaa4bb2b0042daa14cef28be36ac9be5da`, Apache-2.0. DNA tables and hashing code in skani also retain [miniprot's MIT notice](licenses/miniprot.txt).

The lzma-sys, bzip2-sys and tikv-jemalloc-sys notices include the bundled native-code licences. Redistribution of binaries must include this file and the `licenses/` directory, along with Terobacter's own `LICENSE`.

Regenerate after changing `Cargo.lock` with `python3 scripts/generate_license_notices.py`. The script reads the local Cargo source cache and never copies source-cache paths into notices.

| Dependency | Version | Declared licence | Text |
|---|---|---|---|
'''+ '\n'.join(rows)+'\n')
print(len(rows),'runtime dependency notices')
