"""Regenerate or check the licence bundle and supplemental source notices."""

import argparse
import hashlib
import re
import json
import os
from pathlib import Path
import subprocess
import tempfile
import tomllib


BUNDLER_VERSION = "4.2.0"
BUNDLER_REVISION = "d55425c"
ROOT = Path(__file__).resolve().parents[1]
BUNDLE = ROOT / "THIRDPARTY.json"
SUPPLEMENT = ROOT / "THIRD-PARTY-NOTICES.txt"


def run(*command):
    return subprocess.check_output(command, cwd=ROOT, text=True)


def collect_packages(metadata):
    """Retain the previous notice coverage, including transitive build tools."""
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    packages = {package["id"]: package for package in metadata["packages"]}
    pending = [
        dependency["pkg"]
        for dependency in nodes[metadata["resolve"]["root"]]["deps"]
        if any(kind["kind"] != "dev" for kind in dependency["dep_kinds"])
    ]
    seen = set()
    while pending:
        package_id = pending.pop()
        if package_id not in seen:
            seen.add(package_id)
            pending.extend(dependency["pkg"] for dependency in nodes[package_id]["deps"])
    return sorted(
        (packages[package_id] for package_id in seen),
        key=lambda package: (package["name"], package["version"]),
    )


def embedded_packages():
    packages = []
    for name in ['skani', 'partitions']:
        manifest = ROOT / 'vendor' / name / 'Cargo.toml.upstream'
        package = tomllib.loads(manifest.read_text())['package']
        packages.append({**package, 'manifest_path': str(manifest),
                         'authors': package.get('authors', [])})
    return packages


def complete_bundle(bundle):
    for package in embedded_packages():
        name = package['name']
        filename = 'LICENSE' if name == 'skani' else 'LICENSE.txt'
        selected = 'MIT' if name == 'skani' else 'Apache-2.0'
        bundle['third_party_libraries'].append({
            'package_name': name, 'package_version': package['version'],
            'repository': package['repository'], 'license': package['license'],
            'licenses': [{'license': selected,
                          'text': (ROOT / 'vendor' / name / filename).read_text()}],
        })
    bundle['third_party_libraries'].sort(key=lambda p: (p['package_name'], p['package_version']))
    for package in bundle["third_party_libraries"]:
        # skani ships MIT text. Its generic LICENSE is also misidentified as an
        # Apache alternative by the bundler, so select its supplied MIT option.
        if (package["package_name"], package["package_version"]) == ("skani", "0.3.2"):
            package["licenses"] = [
                license for license in package["licenses"] if license["license"] == "MIT"
            ]
        elif "AND" not in package["license"]:
            # Missing alternatives in an OR expression need not be selected.
            package["licenses"] = [
                license for license in package["licenses"] if license["text"] != "NOT FOUND"
            ]
        if not package["licenses"] or any(
            not license["text"].strip() or license["text"] == "NOT FOUND"
            for license in package["licenses"]
        ):
            raise ValueError(
                f"{package['package_name']} {package['package_version']}: missing licence text; "
                "add reviewed text to THIRDPARTY.json and regenerate"
            )
    return bundle


def source_notices(package):
    source = Path(package["manifest_path"]).parent
    files = sorted(
        path for path in source.rglob("*")
        if path.is_file() and path.name.upper().startswith(
            ("LICENSE", "COPYING", "COPYRIGHT", "LICENCE", "NOTICE")
        )
    )
    notices = [(str(path.relative_to(source)), path.read_text(errors="replace")) for path in files]
    if not notices:
        if package["name"] == "cloudabi":
            text = (source / "cloudabi.rs").read_text().split("// This file is automatically generated.")[0]
            notices.append(("cloudabi.rs licence header", "\n".join(
                line.removeprefix("// ") for line in text.splitlines()
            )))
        elif "Apache-2.0" in (package["license"] or ""):
            # Preserve the existing declared Apache option for packages whose
            # source archive omits a dedicated licence file.
            notices.append(("declared Apache-2.0 option", (ROOT / "vendor/partitions/LICENSE.txt").read_text()))
        else:
            raise ValueError(f"{package['name']}: no source licence text")
    return notices


def supplemental_notices(packages, bundle):
    bundled = {
        (package["package_name"], package["package_version"]): "\n".join(
            license["text"] for license in package["licenses"]
        )
        for package in bundle["third_party_libraries"]
    }
    sections = [
        "Supplemental third-party notices\n\n"
        "Generated by scripts/bundle_licenses.py. Ship this file with THIRDPARTY.json.\n"
        "Retains source attribution, build dependency licences and texts absent from the bundle.\n"
    ]
    for package in packages:
        sections.append(
            f"\n=== {package['name']} {package['version']} ===\n\n"
            f"{package['name']} {package['version']}\nDeclared licence: {package['license']}\n"
            f"Authors: {', '.join(package['authors'])}\nRepository: {package['repository'] or ''}\n"
        )
        included = bundled.get((package["name"], package["version"]), "")
        for name, text in source_notices(package):
            if text.strip() not in included:
                sections.append(f"\n--- {name} ---\n\n{text}")
    text = (ROOT / "vendor/skani/src/types.rs").read_text()
    start = text.index("//The MIT License")
    end = text.index("//******************************", start)
    miniprot = "\n".join(line.removeprefix("//").lstrip() for line in text[start:end].splitlines()) + "\n"
    sections.append("\n=== miniprot DNA tables and hashing ===\n\n" + miniprot)
    return "\n".join(sections)



def native_notices():
    """Collect native notices from checked-in sources, not a second text inventory."""
    source = ROOT / "vendor/mummer4"
    paths = {source / name for name in
             ["LICENSE.md", "GPL-3.0.txt", "COPYRIGHT", "ACKNOWLEDGEMENTS", "README.md"]}
    paths.update(path for path in source.rglob("*") if path.is_file() and
                 path.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE")))
    notices = []
    for path in sorted(paths):
        text = path.read_text()
        if not text.strip():
            raise ValueError(f"Empty native notice: {path.relative_to(ROOT)}")
        notices.append({"source": path.relative_to(ROOT).as_posix(), "text": text,
                        "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    # Some native subcomponents supply their grant only in source comments.
    comments = re.compile(r"/\*.*?\*/|(?://[^\n]*(?:\n|$))+", re.DOTALL)
    grant = re.compile(r"copyright|permission is hereby|redistribution and use|"
                       r"free software|distributed under|licensed under", re.IGNORECASE)
    for path in sorted(source.rglob("*")):
        if path.suffix not in {".h", ".hh", ".hpp", ".c", ".cc", ".cpp"}:
            continue
        text = path.read_text()
        for match in comments.finditer(text):
            if grant.search(match.group()):
                notices.append({"source": path.relative_to(ROOT).as_posix(),
                                "line": text.count("\n", 0, match.start()) + 1,
                                "text": match.group()})
    return notices


def distribution_bundle(bundle, supplement):
    """Return a self-contained notice document for binary packages."""
    version = tomllib.loads((ROOT / "Cargo.toml").read_text())["package"]["version"]
    return {
        **bundle,
        "distribution": {
            "scope": "Combined executable: GPL-3.0-or-later. Pterobacter-authored source: MIT. "
                     "Original component grants and notices remain attached to their source.",
            "source": f"https://github.com/mbhall88/pterobacter/releases/download/{version}/"
                      f"pterobacter-{version}-corresponding-source.tar.gz",
            "packaging": "Downstream patches and build scripts must also accompany corresponding "
                         "source; a modified build must provide source for its exact changes.",
            "generated_by": "scripts/bundle_licenses.py --distribution; do not edit by hand",
        },
        "supplemental_notices": supplement.replace(
            "Ship this file with THIRDPARTY.json.",
            "The Cargo licence texts are included in this document."),
        "native_notices": native_notices(),
    }


def distribution_yaml(bundle, supplement):
    # Only the packaging export needs PyYAML; the existing JSON/check workflow
    # remains usable with the Python standard library.
    import yaml
    return yaml.safe_dump(distribution_bundle(bundle, supplement), allow_unicode=True,
                          sort_keys=False, width=100)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on drift without writing files")
    parser.add_argument("--bundler", default="cargo-bundle-licenses", help="path to the pinned executable")
    parser.add_argument("--distribution", type=Path, metavar="YAML",
                        help="generate/check one complete YAML bundle instead of the two upstream files; requires PyYAML")
    args = parser.parse_args()
    version = run(args.bundler, "--version").strip()
    if version not in {
        f"cargo-bundle-licenses cargo:{BUNDLER_VERSION}",
        f"cargo-bundle-licenses git:{BUNDLER_REVISION}",
        # conda-forge cargo-bundle-licenses 4.2.0 builds record this revision.
        "cargo-bundle-licenses git:c1b23d7-modified",
    }:
        raise ValueError(f"expected cargo-bundle-licenses {BUNDLER_VERSION}, found {version}")
    lock = ROOT / "Cargo.lock"
    original_lock = lock.read_bytes()
    metadata = json.loads(run("cargo", "metadata", "--locked", "--offline", "--format-version", "1"))
    packages = sorted(collect_packages(metadata) + embedded_packages(), key=lambda p: (p['name'], p['version']))
    with tempfile.TemporaryDirectory(prefix="pterobacter-licenses-") as directory:
        output = Path(directory) / "bundle.json"
        subprocess.run([
            args.bundler, "--format", "json", "--features", "dev",
            "--previous", str(BUNDLE), "--output", str(output),
        ], cwd=ROOT, env={**os.environ, "CARGO_NET_OFFLINE": "true"}, check=True)
        bundle = complete_bundle(json.loads(output.read_text()))
    if lock.read_bytes() != original_lock:
        raise ValueError("licence generation changed Cargo.lock")
    generated = {
        BUNDLE: json.dumps(bundle, indent=2, ensure_ascii=False) + "\n",
        SUPPLEMENT: supplemental_notices(packages, bundle),
    }
    if args.distribution:
        if args.distribution.resolve() in {BUNDLE.resolve(), SUPPLEMENT.resolve()}:
            raise ValueError("Distribution output must not overwrite upstream licence inputs")
        generated = {args.distribution: distribution_yaml(bundle, generated[SUPPLEMENT])}
    # Compare complete documents, including removed entries and licence texts;
    # the bundler's built-in previous check permits dependency subsets.
    for path, text in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise ValueError(f"{path.name} is stale; regenerate without --check and review the diff")
        else:
            path.write_text(text)
    print(f"{len(bundle['third_party_libraries'])} bundled crates; {len(packages)} attributed source packages; notices {'checked' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
